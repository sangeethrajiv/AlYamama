export const moneyFormat = (val: number, currency = 'SAR') => {
  const formatted = new Intl.NumberFormat('en-US', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(val)
  return `${formatted} ${currency === 'SAR' ? 'SR' : currency}`
}

