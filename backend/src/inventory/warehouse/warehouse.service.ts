import { sequelize } from '../../orm'
import { AppError, notFound } from '../../common.helper'
import { recomputeTree } from '../../common.tree'
import type { RequestEnv } from '../../middleware'
import { Location, PickingType, Warehouse } from './stock.model'
import { LOCATION_TREE } from './location.service'

/**
 * Warehouses and operation types are configuration read from Odoo. Creating a
 * warehouse in Odoo generates a whole set of locations, operation types, routes
 * and pull rules, and changing the reception/delivery steps rewires them; none
 * of that is built yet, so here a warehouse can only be edited in place:
 * name, code, active and partner. The steps are read-only.
 */

export type WarehouseValues = Partial<{ name: string; code: string; active: boolean; partner_id: number | null }>

export async function updateWarehouse(id: number, values: WarehouseValues & Record<string, unknown>, env: RequestEnv): Promise<Warehouse> {
  const locked = ['reception_steps', 'delivery_steps', 'company_id', 'view_location_id', 'lot_stock_id'].filter(k => k in values)
  if (locked.length) {
    throw new AppError(
      `${locked.join(', ')} cannot be changed yet: routes and operation types are generated by Odoo and are not built here.`,
      400,
      'not_supported',
    )
  }
  return sequelize.transaction(async trx => {
    const row = await Warehouse.findByPk(id, { transaction: trx, lock: trx.LOCK.UPDATE })
    if (!row) throw notFound('Warehouse')
    if ('name' in values && !values.name?.trim()) throw new AppError('Name is required.', 400)
    if ('code' in values && !values.code?.trim()) throw new AppError('Short name is required.', 400)
    const patch: Record<string, unknown> = { write_uid: env.uid }
    if (values.name !== undefined) patch.name = values.name.trim()
    if (values.code !== undefined) patch.code = values.code.trim()
    if (values.active !== undefined) patch.active = values.active
    if (values.partner_id !== undefined) patch.partner_id = values.partner_id
    await row.update(patch as never, { transaction: trx })

    // Odoo names a warehouse's view location after its code.
    if (values.code !== undefined) {
      await Location.update({ name: row.code } as never, { where: { id: row.view_location_id }, transaction: trx })
      await recomputeTree(LOCATION_TREE, row.view_location_id, trx)
    }
    return row.reload({ transaction: trx })
  })
}

export type PickingTypeValues = Partial<{ name: string; active: boolean; color: number | null; sequence: number | null; barcode: string | null }>

export async function updatePickingType(id: number, values: PickingTypeValues, env: RequestEnv): Promise<PickingType> {
  return sequelize.transaction(async trx => {
    const row = await PickingType.findByPk(id, { transaction: trx, lock: trx.LOCK.UPDATE })
    if (!row) throw notFound('Operation type')
    if ('name' in values && !values.name?.trim()) throw new AppError('Name is required.', 400)
    await row.update({ ...values, write_uid: env.uid } as never, { transaction: trx })
    return row.reload({ transaction: trx })
  })
}
